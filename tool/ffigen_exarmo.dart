import 'dart:io';

import 'package:ffigen/ffigen.dart';

import 'generate_exarmo_models.dart';

Future<void> main() async {
  final Uri root = Platform.script.resolve('../');
  final Uri source = root.resolve('third_party/exarmo/');
  final Set<String> functions = {};
  final Set<String> globals = {};
  await FfiGenerator(
    input: Input(
      entryPoints: [
        source.resolve('aarch32-capi/include/exarmo/aarch32.h'),
        source.resolve('aarch64-capi/include/exarmo/aarch64.h'),
      ],
      include: (Uri header) => header.path.startsWith(source.path),
    ),
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/third_party/exarmo.g.dart')),
      recordUseMapping: root.resolve(
        'lib/src/third_party/exarmo.record_use_mapping.g.dart',
      ),
      style: const NativeExternalBindings(
        assetId: 'package:disassembler/disassembler.dart',
      ),
      commentType: const CommentType.none(),
      preamble: '''
// Copyright 2026 Vector 35 Inc.
// SPDX-License-Identifier: Apache-2.0
// Generated by package:ffigen
''',
    ),
    visitors: [
      Visitor(
        func: (Func node) {
          node.isIncluded = node.originalName.startsWith('exarmo_');
          node.recordUse = node.isIncluded;
          if (node.isIncluded) functions.add(node.originalName);
        },
        enumClass: (EnumClass node) {
          node.style = EnumStyle.intConstants;
          node.isIncluded = node.originalName.startsWith('exarmo_');
        },
        struct: (Struct node) {
          node.isIncluded = true;
          node.dependencies = CompoundDependencies.full;
        },
        union: (Union node) {
          node.dependencies = CompoundDependencies.full;
        },
        macroConstant: (MacroConstant node) {
          node.isIncluded = node.originalName.startsWith('EXARMO_');
        },
        global: (Global node) {
          node.isIncluded = node.originalName.startsWith('exarmo_');
          if (node.isIncluded) globals.add(node.originalName);
        },
      ),
    ],
  ).generate();
  final StringBuffer exports = StringBuffer(
    '// Copyright (c) 2026, swiftsoft\n'
    '// SPDX-License-Identifier: BSD-3-Clause\n\n'
    '#if defined(_WIN32)\n',
  );
  for (final String symbol in [...functions, ...globals]..sort()) {
    final String decoder = symbol.startsWith('exarmo_aarch32_')
        ? 'ARM'
        : 'AARCH64';
    exports.writeln('#if defined(DISASSEMBLER_EXARMO_$decoder)');
    final String suffix = globals.contains(symbol) ? ',DATA' : '';
    exports.writeln('#if defined(_M_IX86)');
    exports.writeln(
      '#pragma comment(linker, "/EXPORT:$symbol=_$symbol$suffix")',
    );
    exports.writeln('#else');
    exports.writeln('#pragma comment(linker, "/EXPORT:$symbol$suffix")');
    exports.writeln('#endif');
    exports.writeln('#endif');
  }
  exports.writeln('#else');
  exports.writeln(
    '#include "../third_party/exarmo/aarch32-capi/include/exarmo/aarch32.h"',
  );
  exports.writeln(
    '#include "../third_party/exarmo/aarch64-capi/include/exarmo/aarch64.h"',
  );
  exports.writeln('#pragma GCC diagnostic push');
  exports.writeln('#pragma GCC diagnostic ignored "-Wdeprecated-declarations"');
  exports.writeln('__attribute__((used, visibility("default")))');
  exports.writeln('const void *const disassembler_exarmo_exports[] = {');
  for (final String symbol in [...functions, ...globals]..sort()) {
    final String decoder = symbol.startsWith('exarmo_aarch32_')
        ? 'ARM'
        : 'AARCH64';
    exports.writeln('#if defined(DISASSEMBLER_EXARMO_$decoder)');
    exports.writeln('  (const void *)&$symbol,');
    exports.writeln('#endif');
  }
  exports.writeln('};');
  exports.writeln('#pragma GCC diagnostic pop');
  exports.writeln('#endif');
  File.fromUri(root.resolve('src/exarmo_exports.c'))
      .writeAsStringSync(exports.toString());
  await generateExarmoModels(root);
}
